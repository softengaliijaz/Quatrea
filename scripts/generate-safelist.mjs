// Collects every class-like token from the source and writes src/styles/safelist.css.
// Tailwind's normal file scanning still runs; this just guarantees the classes exist even if the scanner
// cannot see the project (ignored folders, unusual paths, some Windows setups).
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(jsx?|html)$/.test(name)) files.push(p);
  }
};
walk('src');
files.push('index.html');

const balanced = (t) => {
  const pairs = { ')': '(', ']': '[' };
  const stack = [];
  for (const ch of t) {
    if (ch === '(' || ch === '[') stack.push(ch);
    else if (pairs[ch] && stack.pop() !== pairs[ch]) return false;
  }
  return stack.length === 0;
};

const tokens = new Set();
for (const file of files) {
  for (const raw of readFileSync(file, 'utf8').split(/[\s"'`]+/)) {
    const t = raw.replace(/^[({,;=>]+|[)};,<]+$/g, '');
    if (!t || t.length > 180 || /[{}$\\;"'`]/.test(t) || !/^[!a-z0-9@\[\-]/i.test(t)) continue;
    if (!balanced(t)) continue; // an unbalanced bracket would invalidate the whole list
    tokens.add(t);
  }
}
const list = [...tokens].sort().join(' ');
writeFileSync('src/styles/safelist.css', `/* Generated by scripts/generate-safelist.mjs. Run \`npm run safelist\` after adding many new classes. */\n@source inline("${list}");\n`);
console.log(`safelist: ${tokens.size} tokens from ${files.length} files`);
